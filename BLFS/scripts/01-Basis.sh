    cd "$ROOT_DIR"
    source "./scripts/$pkg"
done

echo "                                                         "
echo "========================================================="
echo "========================================================="
echo "==                   01   COMPLETE                     =="
echo "==                                                     =="
echo "========================================================="
echo "========================================================="
echo "

