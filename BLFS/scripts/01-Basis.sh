#!/bin/bash
set -euo pipefail

source ./functions.sh

echo "                                                         "
echo "========================================================="
echo "========================================================="
echo "==                   01   START                        =="
echo "==                                                     =="
echo "========================================================="
echo "========================================================="
echo "

scripts=(

cmake
nasm
yasm
unzip
strace
gdb
lsof
pciutils
hwdata
procps-ng

)

for pkg in "${scripts[@]}"; do
